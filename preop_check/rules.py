ALL_RULES = BASE + DIRECTION + AGE + PATHOLOGY_RULES


def applicable_rules(direction: str, age, sex, comorbidities):
    """Базовые + направление + возраст + патологии (каждая отдельной строкой)."""
    direction = (direction or "").strip().lower()
    out = list(BASE)
    out += [r for r in DIRECTION if not r.directions or direction in r.directions]
    if age is not None and age > 60:
        out += AGE
    for c in comorbidities:
        out += [r for r in PATHOLOGY_RULES if r.comorbidity == c]
    if sex:
        s = sex.lower()[:1]
        out = [r for r in out if r.sex is None or r.sex.lower()[:1] == s]
    return out


